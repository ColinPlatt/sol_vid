"""Fetch Base block headers for block-art epochs, rebuild their RLP, check keccak == block hash, and write
test/blockart/BaseEpochs.sol (headers as hex constants) for the Foundry tests.

Usage: python3 scripts/blockart_fixtures.py EPOCH [EPOCH ...]   (epoch e = blocks 10e .. 10e+9)
"""
import json, subprocess, sys, time, urllib.request
from pathlib import Path

RPC = "https://mainnet.base.org"
FIELDS = ["parentHash", "sha3Uncles", "miner", "stateRoot", "transactionsRoot", "receiptsRoot", "logsBloom", "difficulty",
          "number", "gasLimit", "gasUsed", "timestamp", "extraData", "mixHash", "nonce", "baseFeePerGas", "withdrawalsRoot",
          "blobGasUsed", "excessBlobGas", "parentBeaconBlockRoot", "requestsHash", "blockAccessListHash", "slotNumber"]
INTS = {"difficulty", "number", "gasLimit", "gasUsed", "timestamp", "baseFeePerGas", "blobGasUsed", "excessBlobGas", "slotNumber"}


def length(n, off):
    if n < 56:
        return bytes([off + n])
    nb = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([off + 55 + len(nb)]) + nb


def item(b):
    return b if len(b) == 1 and b[0] < 0x80 else length(len(b), 0x80) + b


def header(b):
    out = b""
    for f in FIELDS:
        if f not in b:
            continue
        v = b[f]
        out += item(int(v, 16).to_bytes((int(v, 16).bit_length() + 7) // 8, "big") if f in INTS else bytes.fromhex(v[2:]))
    return length(len(out), 0xc0) + out


def rpc(calls):
    body = json.dumps([{"jsonrpc": "2.0", "id": i, "method": m, "params": p} for i, (m, p) in enumerate(calls)]).encode()
    for attempt in range(5):
        try:
            req = urllib.request.Request(RPC, body, {"Content-Type": "application/json", "User-Agent": "sol_vid-fixtures"})
            reply = json.load(urllib.request.urlopen(req, timeout=30))
            reply = reply if isinstance(reply, list) else [reply]
            if any("error" in r for r in reply):
                raise RuntimeError(reply)
            return [r["result"] for r in sorted(reply, key=lambda r: r["id"])]
        except Exception:
            if attempt == 4:
                raise
            time.sleep(1 + attempt)


def keccak(data):
    return subprocess.check_output(["cast", "keccak", "0x" + data.hex()]).decode().strip()


def main(epochs):
    lines = ["// SPDX-License-Identifier: MIT", "// Generated by scripts/blockart_fixtures.py from Base mainnet; do not edit.",
             "pragma solidity ^0.8.30;", "", "library BaseEpochs {"]
    for e in epochs:
        blocks = rpc([("eth_getBlockByNumber", [hex(10 * e + i), False]) for i in range(10)])
        heads = []
        for b in blocks:
            h = header(b)
            assert keccak(h) == b["hash"], f"header mismatch for block {int(b['number'], 16)}"
            heads.append(h)
        lines.append(f"    // Epoch {e}: blocks {10 * e}..{10 * e + 9}; last hash {blocks[-1]['hash']}")
        lines.append(f"    function epoch{e}() internal pure returns (bytes[] memory h) {{")
        lines.append("        h = new bytes[](10);")
        for i, h in enumerate(heads):
            lines.append(f'        h[{i}] = hex"{h.hex()}";')
        lines.append("    }")
        lines.append(f"    bytes32 internal constant LAST_HASH_{e} = {blocks[-1]['hash']};")
        lines.append("")
        time.sleep(0.6)
    lines[-1] = "}"
    out = Path(__file__).resolve().parent.parent / "test/blockart/BaseEpochs.sol"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(epochs)} epochs)")


if __name__ == "__main__":
    main([int(a) for a in sys.argv[1:]])
