"""Generate src/blockart/Glyphs.sol: 8x8 bitmaps for exactly the characters the block-art scenes draw.

Source font: Misaki Gothic 2nd (美咲ゴシック第2), 8x8, by Num Kadoma, https://littlelimit.net/misaki.htm
(free licence: unlimited use, copying and distribution, with or without modification). Pass the path of
misaki_gothic_2nd.png from the font's PNG archive:

    python3 scripts/blockart_glyphs.py path/to/misaki_gothic_2nd.png
"""
import sys
from pathlib import Path
from PIL import Image

# Sign words, in the order the scenes index them (hash byte 5 % 15), as in concepts/neo-tokyo/kit.js.
WORDS = ["電脳", "暗号", "鍵", "署名", "検証", "連鎖", "量子", "未来", "都市", "零", "壱", "夜市", "光速", "記録", "ベース"]
# Other strings: hologram header, gas label, station, next.
EXTRA = "ブロック・ガス駅次はの"
VBAR = "ー|"  # the long-vowel mark turned upright for vertical text


def main(png):
    im = Image.open(png).convert("L")

    def bits(ch):
        b = ch.encode("euc_jp")
        ku, ten = b[0] - 0xA0, b[1] - 0xA0
        v = 0
        for y in range(8):
            for x in range(8):
                v = v << 1 | (im.getpixel(((ten - 1) * 8 + x, (ku - 1) * 8 + y)) < 128)
        return v

    chars = []
    for ch in "".join(WORDS) + EXTRA:
        if ch not in chars:
            chars.append(ch)
    table = [bits(c) for c in chars]
    # Upright long-vowel mark: transpose ー.
    bar = bits("ー")
    t = 0
    for y in range(8):
        for x in range(8):
            t = t << 1 | (bar >> (63 - (x * 8 + y)) & 1)
    chars.append(VBAR)
    table.append(t)
    index = {c: i for i, c in enumerate(chars)}

    def seq(s, vertical=False):
        return [index[VBAR] if vertical and c == "ー" else index[c] for c in s]

    # Words packed as up to 3 glyph indices (one byte each) plus a length nibble: horizontal and vertical forms.
    def pack(ix):
        v = len(ix)
        for i, g in enumerate(ix):
            v |= g << (8 + 8 * i)
        return v

    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by scripts/blockart_glyphs.py; do not edit.",
        "// Glyphs: Misaki Gothic 2nd 8x8 (c) Num Kadoma, https://littlelimit.net/misaki.htm (free licence).",
        "pragma solidity ^0.8.30;",
        "",
        "/// @notice 8x8 bitmaps for the characters the scenes draw (row-major, MSB = top-left).",
        "library Glyphs {",
        f"    uint256 internal constant COUNT = {len(chars)};",
        f"    uint256 internal constant WORDS = {len(WORDS)};",
        "    /// @dev " + " ".join(f"{i}:{c}" for i, c in enumerate(chars)),
        f'    bytes internal constant TABLE = hex"{"".join(f"{g:016x}" for g in table)}";',
    ]
    lines.append("    /// @dev Sign word w for vertical signs, 4 bytes each: length, then up to 3 glyph indices.")
    vw = b"".join(pack(seq(w, True)).to_bytes(4, "little") for w in WORDS)
    lines.append(f'    bytes internal constant VERTICAL_WORDS = hex"{vw.hex()}";')
    for name, s in [("BASE_BLOCK", "ベース・ブロック"), ("GAS", "ガス"), ("STATION", "駅"), ("NEXT", "次は"), ("NEXT_STATION", "次の駅")]:
        lines.append(f"    /// @dev {s}")
        lines.append(f"    bytes internal constant {name} = hex\"{bytes(seq(s)).hex()}\";")
    lines.append(f"    /// @dev ベース written vertically (torii plaque).")
    lines.append(f"    bytes internal constant BASE_VERTICAL = hex\"{bytes(seq('ベース', True)).hex()}\";")
    lines += [
        "",
        "    function bits(bytes memory table, uint256 g) internal pure returns (uint256 v) {",
        "        assembly (\"memory-safe\") {",
        "            v := shr(192, mload(add(add(table, 32), mul(g, 8))))",
        "        }",
        "    }",
        "",
        "    /// @dev Glyph indices of sign word w (0..14) in vertical form: (length, packed indices).",
        "    function word(uint256 w) internal pure returns (uint256 len, uint256 ix) {",
        "        bytes memory t = VERTICAL_WORDS;",
        "        len = uint8(t[4 * w]);",
        "        ix = uint256(uint8(t[4 * w + 1])) | uint256(uint8(t[4 * w + 2])) << 8 | uint256(uint8(t[4 * w + 3])) << 16;",
        "    }",
        "}",
    ]
    out = Path(__file__).resolve().parent.parent / "src/blockart/Glyphs.sol"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(chars)} glyphs, {len(chars) * 8} bytes")


if __name__ == "__main__":
    main(sys.argv[1])
