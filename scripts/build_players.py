#!/usr/bin/env python3
"""Build src/Players.sol: the onchain HTML players for the AVI and MPEG tokens.

Each player is `data:text/html,` + HEAD + base64(media) + TAIL. HEAD and TAIL are percent-encoded here
(RFC 3986 unreserved and sub-delimiters stay literal), so the contract only inserts base64, which is
already URI- and JSON-safe. Run with --check to verify the checked-in file is current.
"""
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
SAFE = "-_.~!$&'()*+,;=:@/?"
HEAD = ('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
        '<style>html,body{margin:0;height:100%;background:#000;overflow:hidden}'
        'canvas{position:absolute;inset:0;margin:auto;width:100vmin;height:100vmin;image-rendering:pixelated}</style>'
        '</head><body><canvas></canvas><script>const B="')


def script(name):
    # Drop comment-only lines and indentation; the sources carry no `//` inside strings.
    lines = [line.strip() for line in (ROOT / "players" / name).read_text().splitlines()]
    return "\n".join(line for line in lines if line and not line.startswith("//"))


def tail(decoder):
    return '";\n' + script(decoder) + "\n" + script("player.js") + "\n</script></body></html>"


def encode(text):
    encoded = quote(text, safe=SAFE)
    assert re.fullmatch(r"[A-Za-z0-9%\-_.~!$&'()*+,;=:@/?]*", encoded) and '"' not in encoded and "\\" not in encoded
    return encoded


def solidity():
    constants = [("HEAD", HEAD), ("AVI_TAIL", tail("avi.js")), ("MPEG_TAIL", tail("mpeg.js"))]
    body = "".join(f'    string internal constant {name} =\n        "{encode(text)}";\n' for name, text in constants)
    return ("// SPDX-License-Identifier: MIT\n// Generated by scripts/build_players.py from players/*.js. Do not edit.\n"
            "pragma solidity ^0.8.30;\n\n"
            "/// @notice Percent-encoded HTML players; the token's base64 media goes between HEAD and a TAIL.\n"
            "library Players {\n" + body + "}\n")


if __name__ == "__main__":
    out = ROOT / "src" / "Players.sol"
    if "--check" in sys.argv:
        assert out.read_text() == solidity(), "src/Players.sol is stale: run python3 scripts/build_players.py"
        print("src/Players.sol is current.")
    else:
        out.write_text(solidity())
        print(f"Wrote {out.relative_to(ROOT)} ({len(out.read_bytes()):,} bytes).")
